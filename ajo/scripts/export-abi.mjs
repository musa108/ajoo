// Generates packages/abi/src/abis.ts from Foundry build output so web, keeper and scripts share one source of truth.
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const names = ["AjoCircle", "AjoFactory", "ReputationRegistry", "CreditPool", "MockUSD"];

let src = "// AUTO-GENERATED by scripts/export-abi.mjs. Do not edit by hand.\n\n";
for (const n of names) {
  const f = join(out, `${n}.sol`, `${n}.json`);
  if (!existsSync(f)) throw new Error(`Missing artifact ${f}. Run \`forge build\` in contracts/ first.`);
  const abi = JSON.parse(readFileSync(f, "utf8")).abi;
  src += `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}

// bundle every deployment file that exists
const depDir = join(root, "contracts", "deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir)) {
    if (!f.endsWith(".json")) continue;
    const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
src += `export const deployments: Record<number, {\n  chainId: number; token: \`0x\${string}\`; tokenIsMock: boolean; registry: \`0x\${string}\`;\n  factory: \`0x\${string}\`; implementation: \`0x\${string}\`; creditPool: \`0x\${string}\`; deployer: \`0x\${string}\`;\n}> = ${JSON.stringify(deployments, null, 2)} as never;\n`;

writeFileSync(join(root, "packages", "abi", "src", "abis.ts"), src);
console.log("wrote packages/abi/src/abis.ts for", names.join(", "), "| deployments:", Object.keys(deployments).join(", ") || "none");
